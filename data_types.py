age = 25
print(age)
print(type(age))

pi = 3.14
print(pi)
print(type(pi))

name = "Alice"
name_2 = 'Bob'
name_3 = "50"
print(name)
print(type(name))
print(name_2)
print(type(name_2))
print(name_3)
print(type(name_3))

# Boolean values
is_student = True
is_teacher = False
print(is_student)
print(type(is_student))
print(is_teacher)
print(type(is_teacher))

# List of numbers
numbers = [1, 2, 3, 4, 5]
print(numbers)
print(type(numbers))

# Tuple of strings
fruits = ("apple", "banana", "cherry")
print(fruits)
print(type(fruits))

# Dictionary of key-value pairs
person = {"first_name": "Alice", "last_name": "Smith", "age": 25, "is_student": True, "favorite_numbers": [3, 7, 42]}
print(person)
print(person["first_name"])
print(person["last_name"])
print(person["age"])
print(person["is_student"])
print(person["favorite_numbers"])
print(type(person))

# None Type
None_value = None
print(None_value)
print(type(None_value))